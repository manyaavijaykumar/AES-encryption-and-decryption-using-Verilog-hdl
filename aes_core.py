RCON = (0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36)


@dataclass(frozen=True)
class RoundTrace:
    round: int
    operation: str
    state: str
    round_key: str


def parse_hex_block(value: str, label: str = "value") -> bytes:
    clean = "".join(value.split()).replace("0x", "").replace("0X", "")
    if len(clean) != 32:
        raise ValueError(f"{label} must contain exactly 32 hexadecimal characters (128 bits)")
    try:
        return bytes.fromhex(clean)
    except ValueError as exc:
        raise ValueError(f"{label} contains a non-hexadecimal character") from exc


def _hex(values: Iterable[int]) -> str:
    return bytes(values).hex().upper()


def _xor_words(left: list[int], right: list[int]) -> list[int]:
    return [a ^ b for a, b in zip(left, right)]


def key_expansion(key: bytes) -> list[list[int]]:
    if len(key) != 16:
        raise ValueError("AES-128 requires a 16-byte key")
    words = [list(key[index:index + 4]) for index in range(0, 16, 4)]
    for index in range(4, 44):
        temp = words[index - 1][:]
        if index % 4 == 0:
            temp = temp[1:] + temp[:1]
            temp = [S_BOX[value] for value in temp]
            temp[0] ^= RCON[index // 4]
        words.append(_xor_words(words[index - 4], temp))
    return [sum(words[index:index + 4], []) for index in range(0, 44, 4)]


def add_round_key(state: list[int], round_key: list[int]) -> list[int]:
    return [value ^ key_byte for value, key_byte in zip(state, round_key)]


def sub_bytes(state: list[int]) -> list[int]:
    return [S_BOX[value] for value in state]


def inv_sub_bytes(state: list[int]) -> list[int]:
    return [INV_S_BOX[value] for value in state]


def shift_rows(state: list[int]) -> list[int]:
    output = [0] * 16
    for row in range(4):
        for column in range(4):
            output[row + 4 * column] = state[row + 4 * ((column + row) % 4)]
    return output


def inv_shift_rows(state: list[int]) -> list[int]:
    output = [0] * 16
    for row in range(4):
        for column in range(4):
            output[row + 4 * column] = state[row + 4 * ((column - row) % 4)]
    return output


def _gf_mul(left: int, right: int) -> int:
    result = 0
    for _ in range(8):
        if right & 1:
            result ^= left
        high = left & 0x80
        left = (left << 1) & 0xFF
        if high:
            left ^= 0x1B
        right >>= 1
    return result


def mix_columns(state: list[int]) -> list[int]:
    output = state[:]
    for column in range(4):
        index = 4 * column
        a0, a1, a2, a3 = state[index:index + 4]
        output[index:index + 4] = [
            _gf_mul(a0, 2) ^ _gf_mul(a1, 3) ^ a2 ^ a3,
            a0 ^ _gf_mul(a1, 2) ^ _gf_mul(a2, 3) ^ a3,
            a0 ^ a1 ^ _gf_mul(a2, 2) ^ _gf_mul(a3, 3),
            _gf_mul(a0, 3) ^ a1 ^ a2 ^ _gf_mul(a3, 2),
        ]
    return output


def inv_mix_columns(state: list[int]) -> list[int]:
    output = state[:]
    for column in range(4):
        index = 4 * column
        a0, a1, a2, a3 = state[index:index + 4]
        output[index:index + 4] = [
            _gf_mul(a0, 14) ^ _gf_mul(a1, 11) ^ _gf_mul(a2, 13) ^ _gf_mul(a3, 9),
            _gf_mul(a0, 9) ^ _gf_mul(a1, 14) ^ _gf_mul(a2, 11) ^ _gf_mul(a3, 13),
            _gf_mul(a0, 13) ^ _gf_mul(a1, 9) ^ _gf_mul(a2, 14) ^ _gf_mul(a3, 11),
            _gf_mul(a0, 11) ^ _gf_mul(a1, 13) ^ _gf_mul(a2, 9) ^ _gf_mul(a3, 14),
        ]
    return output


def encrypt_block(block: bytes, key: bytes) -> tuple[bytes, list[RoundTrace]]:
    if len(block) != 16 or len(key) != 16:
        raise ValueError("AES-128 encryption requires a 16-byte block and key")
    round_keys = key_expansion(key)
    state = add_round_key(list(block), round_keys[0])
    trace = [RoundTrace(0, "Initial AddRoundKey", _hex(state), _hex(round_keys[0]))]
    for round_number in range(1, 10):
        state = sub_bytes(state)
        state = shift_rows(state)
        state = mix_columns(state)
        state = add_round_key(state, round_keys[round_number])
        trace.append(RoundTrace(round_number, "SubBytes → ShiftRows → MixColumns → AddRoundKey", _hex(state), _hex(round_keys[round_number])))
    state = sub_bytes(state)
    state = shift_rows(state)
    state = add_round_key(state, round_keys[10])
    trace.append(RoundTrace(10, "SubBytes → ShiftRows → AddRoundKey", _hex(state), _hex(round_keys[10])))
    return bytes(state), trace


def decrypt_block(block: bytes, key: bytes) -> tuple[bytes, list[RoundTrace]]:
    if len(block) != 16 or len(key) != 16:
        raise ValueError("AES-128 decryption requires a 16-byte block and key")
    round_keys = key_expansion(key)
    state = add_round_key(list(block), round_keys[10])
    trace = [RoundTrace(10, "Initial AddRoundKey", _hex(state), _hex(round_keys[10]))]
    for round_number in range(9, 0, -1):
        state = inv_shift_rows(state)
        state = inv_sub_bytes(state)
        state = add_round_key(state, round_keys[round_number])
        state = inv_mix_columns(state)
        trace.append(RoundTrace(round_number, "InvShiftRows → InvSubBytes → AddRoundKey → InvMixColumns", _hex(state), _hex(round_keys[round_number])))
    state = inv_shift_rows(state)
    state = inv_sub_bytes(state)
    state = add_round_key(state, round_keys[0])
    trace.append(RoundTrace(0, "InvShiftRows → InvSubBytes → AddRoundKey", _hex(state), _hex(round_keys[0])))
    return bytes(state), trace


def run_aes(mode: str, data_hex: str, key_hex: str) -> dict:
    block = parse_hex_block(data_hex, "Data")
    key = parse_hex_block(key_hex, "Key")
    normalized_mode = mode.strip().lower()
    if normalized_mode == "encrypt":
        output, trace = encrypt_block(block, key)
        recovered, _ = decrypt_block(output, key)
        round_trip_pass = recovered == block
    elif normalized_mode == "decrypt":
        output, trace = decrypt_block(block, key)
        recovered, _ = encrypt_block(output, key)
        round_trip_pass = recovered == block
    else:
        raise ValueError("Mode must be 'encrypt' or 'decrypt'")
    waveform = {
        "duration_ns": 160,
        "clock_period_ns": 10,
        "reset": [[0, 1], [20, 0]],
        "start": [[0, 0], [30, 1], [40, 0]],
        "mode": [[0, 1 if normalized_mode == "decrypt" else 0]],
        "busy": [[0, 0], [40, 1], [150, 0]],
        "done": [[0, 0], [150, 1], [160, 0]],
        "rounds": [{"time_ns": 40 + index * 10, **item.__dict__}
                   for index, item in enumerate(trace)],
        "output_time_ns": 150,
    }
    return {
        "mode": normalized_mode,
        "input": block.hex().upper(),
        "key": key.hex().upper(),
        "output": output.hex().upper(),
        "round_trip_pass": round_trip_pass,
        "trace": [item.__dict__ for item in trace],
        "waveform": waveform,
    }
